'use strict'

/* build-validator.js — precompile data/grammar.schema.json into a
 * standalone Ajv validator at src/grammar-validator.js.
 *
 * WHY. Ajv validates by GENERATING JavaScript for the schema and calling
 * `new Function` on it. Cloudflare Workers refuse that outright:
 *
 *   Code generation from strings disallowed for this context
 *
 * which turns validate_grammar — and every tool that takes a grammar,
 * since all of them validate it first — into a runtime error on the
 * hosted endpoint, while passing every test under Node. Ajv's own
 * answer is `ajv/dist/standalone`: compile the schema at BUILD time and
 * emit the generated function as an ordinary module. Same Ajv, same
 * codegen, same ErrorObject shapes — so the `{path, message}` contract
 * and the golden byte-parity tests are untouched — only the moment of
 * compilation moves, from first call to build.
 *
 * The schema is fixed and bundled, so there is nothing dynamic to lose:
 * precompiling is possible precisely because this service validates
 * against ONE known schema. (A grammar supplied by a caller is DATA
 * checked against that schema; it never becomes a schema itself. If that
 * ever changes, it cannot be precompiled, and it must not be evaluated
 * on the hosted endpoint either — see ADR-10.)
 *
 * GENERATED, NOT COMMITTED: src/grammar-validator.js is in .gitignore
 * and rebuilt by `npm run build` before tsc. tsconfig sets allowJs so
 * tsc copies it to dist/, and the Worker bundle picks up the same file
 * from src/.
 */

const Fs = require('node:fs')
const Path = require('node:path')

const Ajv2020 = require('ajv/dist/2020')
const standaloneCode = require('ajv/dist/standalone').default

const REPO_ROOT = Path.join(__dirname, '..', '..')
const SCHEMA = Path.join(REPO_ROOT, 'data', 'grammar.schema.json')
const OUT = Path.join(__dirname, '..', 'src', 'grammar-validator.js')

function build() {
  const schema = JSON.parse(Fs.readFileSync(SCHEMA, 'utf8'))

  // `allErrors` must match what core.ts used to construct at runtime:
  // validate_grammar reports every problem, not just the first.
  // `code.source` is what makes the compiled function serializable.
  const ajv = new Ajv2020({ allErrors: true, code: { source: true } })

  return [
    '/* GENERATED by tools/build-validator.js — DO NOT EDIT, DO NOT COMMIT.',
    ' * Ajv (draft 2020-12) compiled against data/grammar.schema.json.',
    ' * Regenerate with `npm run build`.',
    ' */',
    standaloneCode(ajv, ajv.compile(schema)),
  ].join('\n')
}

module.exports = { build, SCHEMA, OUT }

if (require.main === module) {
  Fs.writeFileSync(OUT, build())
  console.log('build-validator: wrote ' +
    Path.relative(REPO_ROOT, OUT) +
    ' (' + Fs.statSync(OUT).size + ' bytes)')
}
